// ============================================================
// api/chat.js —— 聊天相关接口方法（HTTP 接口，不是 WebSocket）
// ============================================================
// 【通俗理解】
// 聊天模块用了两种通信方式：
//   1. WebSocket：实时收发消息（useChatWebSocket.js）
//   2. HTTP：查历史消息、会话列表、未读数等（这个文件）
//
// 为什么历史消息用 HTTP 而不是 WebSocket？
//   因为历史消息是"一次性"查询，不需要实时推送。
//   WebSocket 只负责"实时"的新消息推送。
// ============================================================

import request from '../utils/request'

// ============================================================
// 1. 获取与某人的聊天历史
// ============================================================
// GET /api/chat/history/5?productId=10
//   路径参数：5 → 对方的用户ID
//   查询参数：productId=10 → 关联的商品ID（可选）
// 返回：消息数组 [{ id, senderId, content, createTime, ... }]
export const getHistory = (uid, pid) =>
  request.get('/chat/history/' + uid, { params: { productId: pid } })

// ============================================================
// 2. 获取会话列表
// ============================================================
// GET /api/chat/conversations
// 返回：会话数组 [{ userId, nickname, avatarUrl, lastMsg, unread, ... }]
// 用于左侧会话列表
export const getConversations = () => request.get('/chat/conversations')

// ============================================================
// 3. 标记已读
// ============================================================
// PUT /api/chat/read/5
//   路径参数：5 → 发消息的人的用户ID
// 作用：把对方发给我的未读消息标记为已读
export const markRead = (sid) => request.put('/chat/read/' + sid)

// ============================================================
// 4. 获取未读消息总数
// ============================================================
// GET /api/chat/unread
// 返回：未读消息数量
export const getUnread = () => request.get('/chat/unread')