// ============================================================
// vite.config.js —— Vite 构建工具配置文件
// ============================================================
// 【通俗理解】
// Vite 是"打包工具"，负责把 .vue 文件、.js 文件等打包成浏览器能看懂的
// 同时它内置了一个开发服务器（npm run dev 启动的就是它）
// ============================================================

import { defineConfig } from 'vite'     // 导入 Vite 的配置函数
import vue from '@vitejs/plugin-vue'    // 导入 Vue 插件（让 Vite 能解析 .vue 文件）

export default defineConfig({
  // 启用 Vue 插件
  plugins: [vue()],

  // 【开发服务器配置】
  server: {
    port: 5173,  // 前端开发服务器端口号，访问 http://localhost:5173

    // ============================================================
    // 【代理配置】—— 这是前后端联调的关键！
    // ============================================================
    // 【大白话解释】
    // 前端跑在 5173 端口，后端跑在 8080 端口，这是两个不同的"家"
    // 浏览器默认不允许 5173 的网页直接请求 8080 的数据（这叫"跨域限制"）
    //
    // 解决办法：代理
    // 前端不直接请求 8080，而是请求自己的 5173
    // 当请求地址以 /api 开头时，Vite 自动帮你转发到 8080
    //
    // 举例：
    //   前端代码写：request.get('/user/login')
    //   axios 拼成：  /api/user/login  （因为 baseURL 是 /api）
    //   实际请求：    http://localhost:5173/api/user/login
    //   Vite 代理转发：http://localhost:8080/api/user/login  ← 后端实际收到的
    //
    // 这样浏览器以为是请求 5173，实际上数据是从 8080 拿回来的
    // 浏览器就不会报跨域错误了！
    // ============================================================
    proxy: {
      // 规则1：所有以 /api 开头的请求，转发到后端 8080
      '/api': {
        target: 'http://localhost:8080',  // 后端地址
        changeOrigin: true                 // 修改请求头中的 origin，让后端以为是同源请求
      },
      // 规则2：所有以 /uploads 开头的请求（图片文件），也转发到后端 8080
      '/uploads': {
        target: 'http://localhost:8080',
        changeOrigin: true
      }
    }
  }
})